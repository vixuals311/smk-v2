#!/usr/bin/env python3
"""SMK v2 build: inline smk_core into each src/fuses/*.lua -> dist/fuses/*.fuse (self-contained, no require()).
Also copies spikes, validates, and strips junk metadata. Usage: python build/build.py"""
import os, re, shutil, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, "src/core/smk_core.lua")
DIST = os.path.join(ROOT, "dist")
VERSION = open(os.path.join(ROOT, "VERSION")).read().strip()
JUNK = re.compile(r"(^\._|^\.DS_Store$|^Thumbs\.db$)")

def core_block():
    s = open(CORE).read()
    m = re.search(r"-- SMK2_CORE_BEGIN\n(.*?)-- SMK2_CORE_END", s, re.S)
    if not m: sys.exit("core markers missing")
    return m.group(1)

def build_fuses():
    out = os.path.join(DIST, "fuses"); os.makedirs(out, exist_ok=True)
    core = core_block(); built = []
    for f in sorted(os.listdir(os.path.join(ROOT, "src/fuses"))):
        if not f.endswith(".lua"): continue
        body = open(os.path.join(ROOT, "src/fuses", f)).read()
        hdr = f"--[[-- GENERATED by build/build.py (v{VERSION}) — DO NOT EDIT. Source: src/fuses/{f} + src/core/smk_core.lua --]]--\n"
        mods = ""
        for m in re.findall(r"^-- @include (\w+)", body, re.M):
            mt = open(os.path.join(ROOT, "src/core", m + ".lua")).read()
            mm = re.search(r"-- SMK2_MOD_BEGIN\n(.*?)-- SMK2_MOD_END", mt, re.S)
            if not mm: sys.exit(f"{m}: module markers missing")
            mods += mm.group(1) + "\n"
        text = hdr + core + "\n" + mods + body
        if re.search(r"\b(require|dofile|loadfile)\s*\(", text): sys.exit(f"{f}: runtime require/dofile found")
        name = f[:-4] + ".fuse"
        open(os.path.join(out, name), "w", newline="\n").write(text); built.append(name)
    return built

def copy_spikes():
    out = os.path.join(DIST, "spikes"); os.makedirs(out, exist_ok=True)
    for f in sorted(os.listdir(os.path.join(ROOT, "spikes"))):
        if f.endswith(".fuse"): shutil.copy(os.path.join(ROOT, "spikes", f), out)

def package_spike_zip():
    """S5 helper: ZIP of spike Fuses + a minimal .drfx-style layout test. Metadata stripped."""
    zp = os.path.join(DIST, f"SMK2_Phase0_Spikes_v{VERSION}.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for base in ("spikes", "docs/PHASE0_CHECKLIST.md"):
            p = os.path.join(ROOT, base)
            files = [p] if os.path.isfile(p) else [os.path.join(d, x) for d, _, fs in os.walk(p) for x in fs]
            for fp in files:
                if JUNK.match(os.path.basename(fp)): continue
                z.write(fp, os.path.relpath(fp, ROOT))
    return zp

if __name__ == "__main__":
    shutil.rmtree(DIST, ignore_errors=True)
    b = build_fuses(); copy_spikes(); z = package_spike_zip()
    print("built:", ", ".join(b)); print("package:", os.path.relpath(z, ROOT))
